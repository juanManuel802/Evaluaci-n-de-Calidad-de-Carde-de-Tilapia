-- Sync email to correo if correo is empty
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='usuario' AND column_name='email') THEN
        UPDATE usuario SET correo = email WHERE correo IS NULL;
    END IF;
END $$;

